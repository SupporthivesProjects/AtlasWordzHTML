<script>
    document.querySelectorAll('.dropdown_wrap_t').forEach((dropdown) => {
        const trigger = dropdown.querySelector('.dropdown_trigger_t');
        const value = dropdown.querySelector('.dropdown_value_t');
        const input = dropdown.querySelector('.dropdown_input_t');
        const options = dropdown.querySelectorAll('.dropdown_option_t');

        trigger.addEventListener('click', () => {
            dropdown.classList.toggle('is_open_t');
        });

        options.forEach((option) => {
            option.addEventListener('click', () => {
                value.textContent = option.textContent.trim();
                input.value = option.dataset.value;

                dropdown.classList.remove('is_open_t');
            });
        });

        document.addEventListener('click', (event) => {
            if (!dropdown.contains(event.target)) {
                dropdown.classList.remove('is_open_t');
            }
        });
    });



    function field_box_file() {
        console.log('me');
        document.getElementById('document').click();
        }
        $("#document").on("change", function(e){
        document.getElementById('upload_placeholder').innerHTML = e.target.files[0].name;
    })

</script>